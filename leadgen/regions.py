def _city(key: str) -> dict:
    """اطلاعات پایهٔ یک شهر از جدول geo (با نام فارسی).

    ورودی می‌تواند کلید (`tehran`)، نام فارسی («تهران») یا برچسب ترکیبی («تهران، ونک») باشد.
    """
    key = (key or "").strip()
    if key and key not in geo.CITIES:
        resolved = geo.offline_lookup(key)
        if resolved:
            key = resolved
    found = {c["id"]: c for c in geo.known_cities()}.get(key) or {}
    if not found and key in geo.CITIES:
        lat, lon, country, _bbox = geo.CITIES[key]
        found = {"id": key, "label": key.replace("-", " ").title(), "country": country,
                 "lat": lat, "lon": lon, "fa": "", "aliases": []}
    return found


def provinces() -> list[dict]:
    """فهرست استان‌ها + شهرهای هر استان (برای آبشار انتخاب در رابط)."""
    out = []
    for pid, p in PROVINCES.items():
        cities = []
        for key in p["cities"]:
            c = _city(key)
            if not c:
                continue
            cities.append({"id": key, "fa": c.get("fa") or c.get("label", key),
                           "label": c.get("label", key), "lat": c.get("lat"), "lon": c.get("lon"),
                           "districts": len(DISTRICTS.get(key, [])),
                           "streets": len(STREETS.get(key, []))})
        cities.sort(key=lambda c: (c["id"] != p["capital"], c["fa"]))
        capital = _city(p["capital"])
        out.append({
            "id": pid, "fa": p["fa"], "en": p["en"],
            "capital": p["capital"], "capital_fa": capital.get("fa") or capital.get("label", ""),
            "lat": capital.get("lat"), "lon": capital.get("lon"),
            "cities": cities,
        })
    return sorted(out, key=lambda x: x["fa"])


def countries() -> list[dict]:
    """کشورهای غیرایرانی موجود در جدول شهرها (به‌جای استان)."""
    out: dict[str, list[dict]] = {}
    for key, (lat, lon, country, _bbox) in geo.CITIES.items():
        if country == "IR":
            continue
        c = _city(key)
        out.setdefault(country, []).append(
            {"id": key, "fa": c.get("fa") or c.get("label", key), "label": c.get("label", key),
             "lat": lat, "lon": lon, "districts": len(DISTRICTS.get(key, [])),
             "streets": len(STREETS.get(key, []))})
    return [{"id": code, "fa": geo.COUNTRY_FA.get(code, code), "en": code, "cities": sorted(cities, key=lambda c: c["fa"])}
            for code, cities in sorted(out.items())]


def hierarchy() -> dict:
    """کل درخت جغرافیایی در یک بسته (استان‌ها + کشورها)."""
    return {"provinces": provinces(), "countries": countries(),
            "radius": RADIUS, "levels_fa": LEVEL_FA}


