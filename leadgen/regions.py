def _norm(text: str) -> str:
    """نرمال‌سازی متن: نیم‌فاصله → فاصله، حذف فاصله‌های اضافی."""
    return re.sub(r"\s+", " ", (text or "").replace("\u200c", " ").strip())


def _variants(name: str) -> list[str]:
    """چند شکل از یک نام جغرافیایی تا جست‌وجوی متنی قوی‌تر شود.

    «خیابان جردن (نلسون ماندلا)» → [همان، «خیابان جردن»، «جردن»، «Jordan Street»]
    """
    out = [name]
    base = name.split("(")[0].strip()
    if base and base != name:
        out.append(base)
    for prefix in ("خیابان ", "بلوار ", "بزرگراه ", "میدان ", "کوچه ", "بن‌بست "):
        for source in (base, name):
            if source.startswith(prefix):
                short = source[len(prefix):].strip()
                if len(short) >= 3 and short not in out:
                    out.append(short)
    out.extend(LATIN.get(name, []))
    for key, values in LATIN.items():                      # کلیدها هم با نیم‌فاصلهٔ متفاوت می‌آیند
        if _norm(key) == _norm(base) or _norm(key) == _norm(name):
            out.extend(values)
    for latin in list(out):
        short = re.sub(r"\s+(Street|Boulevard|Highway|Square|Road|Avenue|Lane)$", "", latin)
        if short != latin and len(short) >= 3:
            out.append(short)
    seen, uniq = set(), []
    for item in out:
        if item and item not in seen:
            seen.add(item)
            uniq.append(item)
    return uniq


_NAME_CACHE = None


def _name_index() -> list[tuple[str, str, str, str, float, float]]:
    """فهرست (شکل نرمال‌شده، نام اصلی، شهر، نوع، lat، lon) برای جست‌وجوی زیررشته‌ای.

    بلندترین نام اول می‌آید تا «خیابان آزادی» بر «آزادی» برتری داشته باشد.
    """
    global _NAME_CACHE
    if _NAME_CACHE is None:
        rows: list[tuple[str, str, str, str, float, float]] = []
        for city_key, items in DISTRICTS.items():
            for fa, lat, lon in items:
                for variant in _variants(fa):
                    rows.append((_norm(variant).lower(), fa, city_key, "district", lat, lon))
        for city_key, items in STREETS.items():
            for fa, lat, lon, _d in items:
                for variant in _variants(fa):
                    rows.append((_norm(variant).lower(), fa, city_key, "street", lat, lon))
        seen, uniq = set(), []
        for row in rows:
            key = (row[0], row[1], row[2], row[3])
            if key in seen:
                continue
            seen.add(key)
            uniq.append(row)
        # ترتیب اولویت: بلندترین نام؛ سپس نامی که کاربر «کامل» نوشته (پس خیابان ونک بر
        # ونکِ منطقه برتری دارد)؛ و در پایان سطح جزئی‌تر
        uniq.sort(key=lambda r: (-len(r[0]), 0 if r[0] == r[1] else 1,
                                 0 if r[3] == "street" else 1))
        _NAME_CACHE = uniq
    return _NAME_CACHE


def detect_area(text: str, city_key: str = "") -> list[dict]:
    """نام‌های منطقه/خیابانِ شناخته‌شده را **داخل یک جمله** پیدا می‌کند.

    مثال: «کافه در چیتگر تهران» → [{'fa': 'چیتگر', 'kind': 'district', 'city': 'tehran', …}]
    تطبیق‌های تودرتو حذف می‌شوند (مثلاً «آزادی» داخل «خیابان آزادی»).
    """
    text = _norm(text).lower()
    if not text:
        return []
    hits: list[dict] = []
    taken: list[tuple[int, int]] = []
    for variant, canonical, city, kind, lat, lon in _name_index():
        if len(variant) < 3:
            continue
        if city_key and city_key != city:
            continue
        start = text.find(variant)
        while start != -1:
            end = start + len(variant)
            if not any(s < end and start < e for s, e in taken):
                taken.append((start, end))
                hits.append({"fa": canonical, "name": canonical, "matched": variant,
                             "kind": kind, "city": city, "city_fa": city_fa(city),
                             "lat": lat, "lon": lon, "at": start})
                break
            start = text.find(variant, end)
    hits.sort(key=lambda h: h["at"])
    return hits


def best_area(text: str, city_key: str = "") -> dict:
    """دقیق‌ترین نقطهٔ داخل جمله: خیابان > منطقه (وگرنه {})."""
    hits = detect_area(text, city_key)
    if not hits:
        return {}
    for kind in ("street", "district"):
        for hit in hits:
            if hit["kind"] == kind:
                return hit
    return hits[0]


def area_keywords(text: str) -> list[str]:
    """نام‌های جغرافیاییِ پیدا‌شده در جمله (برای هایلایت در رابط)."""
    return [hit["fa"] for hit in detect_area(text)]


def search_areas(text: str, limit: int = 8) -> list[dict]:
    """پیشنهاد زندهٔ منطقه/خیابان برای جعبهٔ جست‌وجو (فارسی، لاتین و تقریبی)."""
    needle = _norm(text).lower()
    if not needle:
        return []
    hits: list[tuple[float, dict]] = []
    seen: set[str] = set()
    for variant, canonical, city, kind, lat, lon in _name_index():
        score = _score(needle, variant)
        if not score:
            continue
        city_name = city_fa(city)
        label = f"{canonical} — {city_name}"
        key = f"{city}|{canonical}|{kind}"
        if key in seen or label in seen:
            continue
        seen.add(key)
        seen.add(label)
        hits.append((score, {"kind": kind, "fa": canonical, "name": canonical,
                             "matched": variant, "city": city, "city_fa": city_name,
                             "province": CITY_PROVINCE.get(city, ""), "lat": lat, "lon": lon,
                             "label": label}))
    hits.sort(key=lambda x: (-x[0], x[1]["label"]))
    return [item for _score_value, item in hits[:limit]]
