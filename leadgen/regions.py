def city(key_or_name: str) -> dict:
    """اطلاعات یک شهر برای رابط: id/fa/label/lat/lon/country + تعداد منطقه و خیابان."""
    c = dict(_city(key_or_name))
    if not c:
        return {}
    c["districts"] = len(DISTRICTS.get(c.get("id", ""), []))
    c["streets"] = len(STREETS.get(c.get("id", ""), []))
    c["province"] = CITY_PROVINCE.get(c.get("id", ""), "")
    return c


def districts(city_key: str) -> list[dict]:
    rows = [{"id": i, "fa": fa, "lat": lat, "lon": lon, "kind": "district"}
            for i, (fa, lat, lon) in enumerate(DISTRICTS.get(city_key, []))]
    # محله‌های قدیمی geo که اینجا نیامده‌اند هم اضافه می‌شوند (بدون مختصات)
    have = {r["fa"] for r in rows}
    for name in geo.NEIGHBORHOODS.get(city_key, []):
        if name not in have:
            rows.append({"id": len(rows), "fa": name, "lat": None, "lon": None, "kind": "neighborhood"})
    return rows


def streets(city_key: str, district: str = "") -> list[dict]:
    rows = [{"id": i, "fa": fa, "lat": lat, "lon": lon, "district": d, "kind": "street"}
            for i, (fa, lat, lon, d) in enumerate(STREETS.get(city_key, []))]
    if district:
        filtered = [r for r in rows if district.split("(")[0].strip() in r["district"]
                    or r["district"] in district]
        rows = filtered or rows
    return rows


def find_area(text: str, city_key: str = "", level: str = "") -> dict | None:
    """یک نام منطقه/خیابان/شهر → نقطهٔ آن (با تحمل غلط تایپی و نام لاتین).

    جست‌وجو روی فهرست نام‌های نرمال‌شده انجام می‌شود، پس «Vanak»، «ونک» و «خیابان ونک»
    هر سه به یک نقطه می‌رسند. اگر شهر داده شود، فقط همان شهر جست‌وجو می‌شود؛ بخش شهرها
    تنها وقتی فعال است که سطح خواسته‌شده `city` (یا نامشخص) باشد — وگرنه «ونک» به
    «ونکوور» گره می‌خورد!
    """
    needle = _norm(text).lower()
    if not needle:
        return None
    city_filter = _city(city_key).get("id", "") if city_key else ""
    best: tuple[float, dict] | None = None
    for variant, canonical, city, kind, lat, lon in _name_index():
        if level and kind != level:
            continue
        if city_filter and city_filter != city:
            continue
        score = _score(needle, variant)
        if score and (best is None or score > best[0]):
            best = (score, {"kind": kind, "fa": canonical, "matched": variant,
                            "lat": lat, "lon": lon, "city": city})
    if level in ("", "city"):
        # نام شهرها هم رقابت می‌کنند (وگرنه «تهران» به «تهرانپارس» می‌چسبد)
        for key, (lat, lon, _country, _b) in geo.CITIES.items():
            c = _city(key)
            for name in [c.get("fa", ""), c.get("label", ""), *c.get("aliases", [])]:
                score = _score(needle, _norm(name).lower())
                if score and (best is None or score > best[0]):
                    best = (score, {"kind": "city", "fa": name, "matched": needle,
                                    "lat": lat, "lon": lon, "city": key})
    return best[1] if best else None


def _score(needle: str, hay: str) -> float:
    hay = (hay or "").strip().lower()
    if not hay:
        return 0.0
    if hay == needle:
        return 1.0
    if hay.startswith(needle):
        return 0.92
    if needle in hay:
        return 0.80
    ratio = SequenceMatcher(None, needle, hay).ratio()
    return ratio * 0.75 if ratio >= 0.62 else 0.0


def resolve(province: str = "", city: str = "", district: str = "", street: str = "",
            lat: float | None = None, lon: float | None = None, lang: str = "fa") -> dict:
    """انتخاب‌های کاربر → یک نقطه + شعاع + برچسب خوانا.

    اولویت: خیابان > منطقه > شهر > استان > مختصات دستی.
    اگر سطحی مختصات نداشته باشد، به سطح بالاتر برمی‌گردد و شعاع را همان نگه می‌دارد.
    """
    label_parts: list[str] = []
    point: tuple[float, float] | None = None
    level = ""
    city_key = _city(city).get("id", "") if city else ""

    if street:
        hit = find_area(street, city_key, level="street") or find_area(street, "", "street")
        label_parts.append(hit["fa"] if hit else street)
        if hit and hit["lat"]:
            point, level = (hit["lat"], hit["lon"]), "street"
            city_key = city_key or hit["city"]
    if district:
        hit = find_area(district, city_key, level="district") or find_area(district, "", "district")
        label_parts.append(hit["fa"] if hit else district)
        if not point:
            if hit and hit["lat"]:
                point, level = (hit["lat"], hit["lon"]), "district"
                city_key = city_key or hit["city"]
        elif not level:
            level = "district"
    if city_key:
        c = _city(city_key)
